"""Figure and REPORT.md writer for review (plain Markdown, numbers only, no interpretation)."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from componergy.review.data import HEADLINE
from componergy.review.models import P_TYPES


def md_table(df: pd.DataFrame, digits: int = 4) -> str:
    if df is None or len(df) == 0:
        return "_(empty)_\n"

    def fmt(v):
        if isinstance(v, (float, np.floating)):
            if not np.isfinite(v):
                return "NaN"
            return f"{v:.{digits}g}" if abs(v) < 1e4 else f"{v:.0f}"
        return str(v)

    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(fmt(r[c]) for c in cols) + " |")
    return "\n".join(lines) + "\n"


def nullsim_figure(rejection: pd.DataFrame, path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    terms = ["Compound", "A", "hd"]
    gens = ["N1", "N2"]
    colors = plt.get_cmap("tab10")(np.arange(len(HEADLINE)))
    fig, axes = plt.subplots(len(terms), len(gens), figsize=(11, 9), sharey=True)
    for i, term in enumerate(terms):
        for j, g in enumerate(gens):
            ax = axes[i, j]
            sub = rejection[(rejection["generator"] == g) & (rejection["term"] == term)]
            for k, s in enumerate(HEADLINE):
                for x, pt in enumerate(P_TYPES):
                    r = sub[(sub["series"] == s) & (sub["p_type"] == pt)]
                    if r.empty:
                        continue
                    r = r.iloc[0]
                    xx = x + (k - 3) * 0.09
                    ax.errorbar(xx, r["rate"], yerr=[[max(r["rate"] - r["wilson_lo"], 0.0)], [max(r["wilson_hi"] - r["rate"], 0.0)]],
                                fmt="o", ms=4, color=colors[k], elinewidth=1, label=s if (i, j, x) == (0, 0, 0) else None)
            ax.axhline(0.05, color="k", lw=1)
            ax.set_xticks(range(len(P_TYPES)))
            ax.set_xticklabels([p.replace("p_", "") for p in P_TYPES], rotation=20, fontsize=8)
            ax.set_title(f"{g}: {'placebo climate, descriptive; not used for calibration' if g == 'N1' else 'VAR climate'} - {term}", fontsize=10)
            if j == 0:
                ax.set_ylabel("rejection rate at 0.05")
    axes[0, 0].legend(fontsize=7, ncol=2, frameon=False)
    fig.tight_layout()
    fig.savefig(path, dpi=300)
    plt.close(fig)


def _load(out: Path, rel: str):
    p = out / rel
    return pd.read_csv(p) if p.exists() else None


def _sec(title, body):
    return f"\n## {title}\n\n{body}\n"


def _rate_table(rej: pd.DataFrame, conditional: bool = False) -> pd.DataFrame:
    r = rej[rej["term"].isin(["Compound", "A", "hd"]) & rej["series"].isin(HEADLINE)].copy()
    pre = "cond_" if conditional else ""
    if conditional:
        r = r[r["generator"] == "N2"]
    r["cell"] = r.apply(lambda x: f"{x[pre + 'rate']:.3f} [{x[pre + 'wilson_lo']:.3f}, {x[pre + 'wilson_hi']:.3f}]",
                        axis=1)
    p = r.pivot_table(index=["generator", "series", "term"], columns="p_type", values="cell", aggfunc="first")
    p = p[[c for c in P_TYPES if c in p.columns]].reset_index()
    p["n_draws"] = r.groupby(["generator", "series", "term"])[pre + "n_draws"].min().values
    p.loc[p["generator"] == "N1", "generator"] = "N1 (descriptive; not used for calibration)"
    return p


def build_report(out: Path, meta: dict) -> str:
    out = Path(out)
    L = ["# Review report\n", "Numbers only; no interpretation. Generated by `python -m scripts.run_review`.\n"]

    fz = meta.get("Freeze check", {})
    L.append(_sec("1. Freeze check", "\n".join(
        f"- {k}: {v}" for k, v in fz.items()) or "_(not run)_"))

    rep = meta.get("Reproduction")
    L.append(_sec("2. Reproduction checks (max |difference| against the published figure CSVs)",
                  md_table(pd.DataFrame(rep), 3) if rep else "_(not run)_"))

    choice = out / "b3" / "b3_choice.json"
    s3 = []
    if choice.exists():
        s3.append("### b3_choice.json\n\n```json\n" + choice.read_text(encoding="utf-8") + "\n```\n")
    rej = _load(out, "b3/b3_nullsim_rejection.csv")
    if rej is not None:
        s3.append("### Rejection rate at 0.05, unconditional (Wilson 95% interval), headline series\n\n"
                  "N1 is descriptive; not used for calibration.\n\n" + md_table(_rate_table(rej)))
        s3.append("### N2 rejection rate conditional on the compound count within +-25% of observed\n\n"
                  + md_table(_rate_table(rej, conditional=True)))
    dg = _load(out, "b3/b3_nullsim_diagnostics.csv")
    if dg is not None:
        dg = dg.copy()
        dg["flag"] = np.where(dg["outside_5_95"], "OUTSIDE 5-95%", "")
        dg.loc[dg["generator"] == "N1", "generator"] = "N1 (descriptive; not used for calibration)"
        s3.append("### Simulation diagnostics (observed vs simulated median and 5-95%)\n\n" + md_table(dg))
    ee = _load(out, "b3/b3_effective_events.csv")
    if ee is not None:
        s3.append("### Effective events\n\n" + md_table(ee))
    ep = _load(out, "b3/b3_episodes.csv")
    if ep is not None:
        s3.append("### Compound episodes (merge gap 12 months)\n\n" + md_table(ep))
    L.append(_sec("3. B3: calibration of the p-values", "\n".join(s3) or "_(not run)_"))

    cmp_ = _load(out, "b3/b3_inference_comparison.csv")
    if cmp_ is not None:
        keep = ["Series", "Term", "N", "estimate", "unit", "p_norm_shift", "p_exact_shift", "p_exact_season",
                "p_yearperm", "p_hac", "CI_boot_lo", "CI_boot_hi", "est_season", "est_water", "p_chosen",
                "q_norm_shift", "q_chosen", "n_boot_dropped"]
        body = md_table(cmp_[cmp_["Term"].isin(["Compound", "A"])][keep])
    else:
        body = "_(not run)_"
    L.append(_sec("4. B3a: same estimate, every p-type, bootstrap CI (headline series)", body))

    bi = _load(out, "b1/b1_intensity_conditioned.csv")
    ds = _load(out, "b1/b1_driver_summary.csv")
    s5 = []
    if bi is not None:
        s5.append(md_table(bi))
    if ds is not None:
        s5.append("### h and d by event type\n\n" + md_table(ds))
    L.append(_sec("5. B1b: compound effect with and without h, d controls", "\n".join(s5) or "_(not run)_"))

    co = _load(out, "b1/b1_continuous_coefficients.csv")
    mc = _load(out, "b1/b1_model_comparison.csv")
    mh = _load(out, "b1/b1_marginal_heat.csv")
    dec = _load(out, "b1/b1_decision.csv")
    s6 = []
    if co is not None:
        h7 = co[co["Series"].isin(HEADLINE)]
        m2 = h7[(h7["Model"] == "M2")].pivot_table(index="Series", columns="Term", values="estimate")
        s6.append("### M2: b_h, b_d, b_hd\n\n" + md_table(m2.reset_index()))
        cols = ["Series", "Model", "Term", "estimate", "p_chosen", "chosen_p_type", "p_norm_shift", "p_yearperm",
                "p_hac", "CI_boot_lo", "CI_boot_hi"]
        s6.append("### b_hd (M2) and the h x d12 term (M2w')\n\n" + md_table(
            h7[((h7["Model"] == "M2") & (h7["Term"] == "hd")) | ((h7["Model"] == "M2w'") & (h7["Term"] == "h_x_d12"))][cols]))
    if mc is not None:
        piv = mc[mc["Series"].isin(HEADLINE)].pivot_table(index="Series", columns="Model", values="cv_rmse")
        s6.append("### Leave-one-water-year-out CV RMSE\n\n" + md_table(piv.reset_index()))
        s6.append("### R2 and increments\n\n" + md_table(mc[mc["Series"].isin(HEADLINE)]))
    if mh is not None:
        s6.append("### Marginal heat effect b_h + b_hd * d\n\n" + md_table(mh[mh["Series"].isin(HEADLINE)]))
    if dec is not None:
        s6.append("### Decision-rule flags (mechanical)\n\n" + md_table(dec[dec["Series"].isin(HEADLINE)]))
    L.append(_sec("6. B1c: continuous interaction models", "\n".join(s6) or "_(not run)_"))

    sp = _load(out, "b2/b2_specifications.csv")
    s7 = []
    four = ["Fossil share", "Hydro share", "Fossil GWh", "Hydro GWh"]
    if sp is not None:
        s7.append("### Specifications (Compound)\n\n" + md_table(
            sp[sp["Series"].isin(four) & (sp["Term"] == "Compound")][
                ["Series", "Spec", "N", "estimate", "unit", "Delta_pct", "p_norm_shift", "p_exact_shift",
                 "p_exact_season", "p_yearperm", "p_hac", "p_chosen", "CI_boot_lo", "CI_boot_hi"]]))
    for rel, title, flt in (("b2/b2_leave_one_episode_out.csv", "Leave-one-episode-out", True),
                            ("b2/b2_jackknife_year.csv", "Drop-one-calendar-year jackknife", True),
                            ("b2/b2_substitution.csv", "Substitution accounting", False),
                            ("b2/b2_share_decomposition.csv", "Share decomposition", False),
                            ("b2/b2_decision.csv", "Decision-rule flags (mechanical)", False)):
        d = _load(out, rel)
        if d is not None:
            if flt and "Series" in d:
                d = d[d["Series"].isin(four)]
            s7.append(f"### {title}\n\n" + md_table(d))
    L.append(_sec("7. B2: portfolio robustness", "\n".join(s7) or "_(not run)_"))

    ad = out / "addons.json"
    L.append(_sec("8. Add-ons", "```json\n" + ad.read_text(encoding="utf-8") + "\n```" if ad.exists() else "_(not run)_"))

    run = meta.get("Run", {})
    L.append(_sec("9. Run", "\n".join(f"- {k}: {v}" for k, v in run.items()) or "_(not run)_"))
    text = "".join(L)
    tmp = out / "REPORT.md.tmp"
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(out / "REPORT.md")
    return text
